const DICT = { en, de };

function detect() {
  if (!I18N_ENABLED) return 'en';
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && DICT[saved]) return saved;
  } catch { /* storage unavailable */ }
  const nav = (navigator.languages?.[0] || navigator.language || 'en').toLowerCase();
  return nav.startsWith('de') ? 'de' : 'en';
}

let lang = detect();
document.documentElement.lang = lang;

export const getLang = () => lang;

export function setLang(next) {
  if (!DICT[next]) return;
  lang = next;
  document.documentElement.lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* fine */ }
}

/** Locale for dates/times: the browser's own region when it matches the app language (en-GB, de-AT…). */
export function locale() {
  const nav = navigator.language || '';
  return nav.toLowerCase().startsWith(lang) ? nav : lang;
}

export function t(key, ...args) {
  const v = DICT[lang][key] ?? DICT.en[key];
  if (v == null) {
    console.warn(`[i18n] missing key: ${key}`);
    return key;
  }
  return typeof v === 'function' ? v(...args) : v;
}
